import { chromium, expect } from "@playwright/test";
import fs from "node:fs/promises";
const browser = await chromium.launch({ channel: process.env.QA_BROWSER || "chrome", headless: true });
const context = await browser.newContext({ viewport: { width: 1600, height: 1000 }, locale: "ko-KR" });
const page = await context.newPage(), errors = [], checks = [];
const base = process.env.QA_URL || "http://localhost:4173";
page.on("pageerror", (e) => { errors.push(e.message); console.log("ERROR", e.message); });
page.on("console", (m) => { if (m.type() === "error") { errors.push(m.text()); console.log("ERROR", m.text()); } });
const check = (name, result) => { checks.push({ name, passed: Boolean(result) }); expect(result, name).toBeTruthy(); console.log("PASS", name); };
const read = () => page.evaluate(() => window.__vastness.inspect());
try {
  await fs.mkdir("artifacts", { recursive: true });
  await page.goto(base + "/?qa=1");
  await page.locator("main[data-ready=true]").waitFor({ timeout: 120000 });
  await page.locator('[data-step="welcome"]').waitFor();
  check("Korean browser opens Korean welcome", await page.getByRole("heading", { name: "잠깐, 쉬어 가세요." }).isVisible());
  await expect(page.locator(".welcome-guide")).toHaveCSS("opacity", "1");
  await page.screenshot({ path: "artifacts/onboarding-korean.png" });
  await page.getByRole("button", { name: "English", exact: true }).click();
  check("Welcome can switch to English", await page.getByRole("heading", { name: "A little room to breathe." }).isVisible());
  await page.getByRole("button", { name: "한국어", exact: true }).click();
  await page.getByRole("button", { name: /움직이는 법 알아보기/ }).click();
  await page.locator('[data-step="look"]').waitFor();
  check("Instruction does not cover the central canvas", await page.evaluate(() => document.elementFromPoint(800, 400)?.tagName === "CANVAS"));
  await page.mouse.click(850, 390);
  await page.waitForTimeout(150);
  check("Guide click acquires actual pointer lock", await page.evaluate(() => document.pointerLockElement?.tagName === "CANVAS"));
  await page.mouse.move(950, 410, { steps: 8 });
  await page.locator('[data-step="move"]').waitFor();
  check("Actual mouse look advances the guide", (await read()).learning.look > 0.075);
  const before = (await read()).position;
  await page.keyboard.down("w"); await page.waitForTimeout(1200); await page.keyboard.up("w");
  await page.locator('[data-step="speed"]').waitFor();
  check("Actual W movement advances the guide", Math.hypot(...(await read()).position.map((p, i) => p - before[i])) > 1.5);
  await page.mouse.wheel(0, -160);
  await page.locator('[data-step="done"]').waitFor();
  check("Wheel speed change completes the guide", (await read()).speedDial > 1.1);
  await expect.poll(() => page.evaluate(() => Boolean(document.pointerLockElement))).toBe(false);
  check("Completed guide returns the cursor for its visible choices", !await page.evaluate(() => Boolean(document.pointerLockElement)));
  await page.getByRole("button", { name: "어디로 갈까", exact: false }).click();
  await page.getByRole("button", { name: "다른 행성과 먼 우주", exact: true }).click();
  check("All five distinct distant planets are accessible", await page.locator('[data-destination="giant"], [data-destination="moon"], [data-destination="ember"], [data-destination="serein"], [data-destination="nacre"]').count() === 5);
  await page.getByRole("button", { name: "패널 닫기" }).click();
  await page.reload();
  await page.locator("main[data-ready=true]").waitFor({ timeout: 120000 });
  await page.waitForTimeout(500);
  check("Completed guide stays dismissed after reload", await page.locator(".arrival-guide").count() === 0);
  check("Korean preference and document language persist", await page.evaluate(() => document.documentElement.lang === "ko" && localStorage.getItem("vastness-language") === "ko"));
  await page.keyboard.press("h");
  await page.getByRole("button", { name: /움직이는 법 다시 배우기/ }).click();
  check("Help can replay the movement guide", await page.locator('[data-step="welcome"]').isVisible());
  await page.getByRole("button", { name: "풍경에 맡기기", exact: true }).last().click();
  await page.waitForTimeout(250);
  check("Welcome wander works without mandatory lessons", (await read()).mode === "WANDER");
  await page.keyboard.down("w"); await page.waitForTimeout(80);
  check("Manual input immediately overrides welcome wander", (await read()).mode === "FREE");
  await page.keyboard.up("w"); await page.keyboard.press("r");
  await page.mouse.click(900, 400); await page.waitForTimeout(120); await page.keyboard.press("m");
  await page.getByRole("button", { name: "패널 닫기" }).waitFor();
  check("M releases pointer lock and opens an operable menu", !await page.evaluate(() => Boolean(document.pointerLockElement)));
  await page.getByRole("button", { name: "패널 닫기" }).click();
  await page.getByRole("button", { name: "편안하게 설정", exact: true }).click();
  await page.getByRole("button", { name: "English", exact: true }).click();
  check("Settings and labels switch language immediately", await page.getByLabel("Look sensitivity").isVisible());
  await page.getByRole("button", { name: "Close panel" }).click();
  await page.keyboard.press("h");
  check("English help remains accessible", await page.getByRole("complementary", { name: "Flight controls" }).isVisible());
  await page.screenshot({ path: "artifacts/onboarding-english-help.png" });
  check("No horizontal overflow", await page.evaluate(() => document.documentElement.scrollWidth === innerWidth));
  check("No runtime or shader errors", errors.length === 0);
} finally {
  await fs.writeFile("artifacts/onboarding-qa.json", JSON.stringify({ url: base, browser: await browser.version(), checks, errors }, null, 2));
  await browser.close();
}
